std::uint64_t zobrist_piece(Color color, Piece type, Square square) noexcept {
    if ((color != White && color != Black) || type < Pawn || type > King || square < 0 || square >= 64) return 0;
    return kPieceZobrist[color][type][square];
}

std::uint64_t zobrist_en_passant(Square square) noexcept {
    return square >= 0 && square < 64 ? kEnPassantZobrist[square] : 0;
}

std::uint64_t zobrist_castling(std::uint8_t rights) noexcept {
    return kCastlingZobrist[rights & 15];
}

std::uint64_t zobrist_side() noexcept { return kSideZobrist; }

HashValues calculate_hashes(const Position& p) noexcept {
    HashValues result;
    for (Square square = 0; square < 64; ++square) {
        const int signed_piece = p.board[square];
        if (!signed_piece) continue;
        const Color color = signed_piece > 0 ? White : Black;
        const Piece type = static_cast<Piece>(signed_piece > 0 ? signed_piece : -signed_piece);
        const std::uint64_t key = zobrist_piece(color, type, square);
        result.key ^= key;
        if (type == Pawn) result.pawn_key ^= key;
        else result.non_pawn_key[color] ^= key; // Booot includes kings in NonPawnKey.
        result.non_pawn_material[color] += piece_material(type);
    }
    if (p.en_passant != kNoSquare) result.key ^= zobrist_en_passant(p.en_passant);
    result.key ^= zobrist_castling(p.castling_rights);
    if (p.side_to_move == Black) result.key ^= zobrist_side();
    return result;
}

void recompute_hashes(Position& p) noexcept {
    const HashValues h = calculate_hashes(p);
    p.key = h.key;
    p.pawn_key = h.pawn_key;
    p.non_pawn_key = h.non_pawn_key;
    p.non_pawn_material = h.non_pawn_material;
}

bool hash_values_match(const Position& p) noexcept {
    const HashValues h = calculate_hashes(p);
    return p.key == h.key && p.pawn_key == h.pawn_key &&
           p.non_pawn_key == h.non_pawn_key &&
           p.non_pawn_material == h.non_pawn_material;
}

int value_to_tt(int value, int ply, int win_score, int infinity) noexcept {
    if (value >= win_score) return value + ply;
    if (value != -infinity && value <= -win_score) return value - ply;
    return value;
}

int value_from_tt(int value, int ply, int win_score, int infinity) noexcept {
    if (value >= win_score) return value - ply;
    if (value != -infinity && value <= -win_score) return value + ply;
    return value;
}

